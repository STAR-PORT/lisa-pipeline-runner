#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG_FILE="${1:-$SCRIPT_DIR/.env}"

if [ "$(id -u)" -ne 0 ]; then
  echo "Run as root (use sudo)"
  exit 1
fi

if [[ -f "$CONFIG_FILE" ]]; then
  echo "Loading Kubernetes setup configuration from $CONFIG_FILE"
  set -a
  source "$CONFIG_FILE"
  set +a
else
  echo "Configuration file not found: $CONFIG_FILE"
  echo "Create the file by copying $SCRIPT_DIR/.env.example and editing it."
  exit 1
fi

HPC_FORWARD_BIND_ADDRESS="${HPC_FORWARD_BIND_ADDRESS:-10.1.0.2}"
OBJECT_STORE_FORWARD_PORT="${OBJECT_STORE_FORWARD_PORT:-19001}"
K8S_API_FORWARD_PORT="${K8S_API_FORWARD_PORT:-19002}"
K8S_NODE_IP="${K8S_NODE_IP:-$(ip -4 route get 1.1.1.1 | awk '{for (i=1; i<=NF; i++) if ($i == "src") {print $(i+1); exit}}')}"
OBJECT_STORE_NODE_PORT="${OBJECT_STORE_NODE_PORT:-30900}"
OBJECT_STORE_CONSOLE_NODE_PORT="${OBJECT_STORE_CONSOLE_NODE_PORT:-30901}"
OBJECT_STORE_BUCKET="${OBJECT_STORE_BUCKET:-lisa}"
OBJECT_STORE_ENDPOINT="${OBJECT_STORE_ENDPOINT:-http://${HPC_FORWARD_BIND_ADDRESS}:${OBJECT_STORE_FORWARD_PORT}}"
KUBERNETES_API_ENDPOINT="https://${HPC_FORWARD_BIND_ADDRESS}:${K8S_API_FORWARD_PORT}"
MACHINE_HOST="${MACHINE_HOST:-$K8S_NODE_IP}"
export K8S_NODE_IP MACHINE_HOST OBJECT_STORE_ENDPOINT OBJECT_STORE_BUCKET KUBERNETES_API_ENDPOINT

echo "Running Kubernetes setup with the following values:"
echo "  K8S_VERSION=$K8S_VERSION"
echo "  K8S_FULL_VERSION=$K8S_FULL_VERSION"
echo "  K8S_PKG_VERSION=$K8S_PKG_VERSION"
echo "  K8S_NODE_IP=${K8S_NODE_IP:-auto-detected by kubeadm setup}"
echo "  KUBERNETES_API_ENDPOINT=$KUBERNETES_API_ENDPOINT"
echo "  CALICO_VERSION=$CALICO_VERSION"
echo "  ARGO_VERSION=$ARGO_VERSION"
echo "  INTERLINK_VERSION=$INTERLINK_VERSION"
echo "  INTERLINK_INSTALL_DIR=$INTERLINK_INSTALL_DIR"
echo "  SIDECAR_SSH_USER=$SIDECAR_SSH_USER"
echo "  SIDECAR_SSH_HOST=$SIDECAR_SSH_HOST"
echo "  SIDECAR_LOCAL_HOST=$SIDECAR_LOCAL_HOST"
echo "  SIDECAR_LOCAL_PORT=$SIDECAR_LOCAL_PORT"
echo "  SIDECAR_REMOTE_PORT=$SIDECAR_REMOTE_PORT"
echo "  HPC_FORWARD_BIND_ADDRESS=$HPC_FORWARD_BIND_ADDRESS"
echo "  OBJECT_STORE_FORWARD_PORT=$OBJECT_STORE_FORWARD_PORT"
echo "  K8S_API_FORWARD_PORT=$K8S_API_FORWARD_PORT"
echo "  OBJECT_STORE_NODE_PORT=$OBJECT_STORE_NODE_PORT"
echo "  OBJECT_STORE_ENDPOINT=$OBJECT_STORE_ENDPOINT"
echo "  OBJECT_STORE_BUCKET=$OBJECT_STORE_BUCKET"
echo "  INTERLINK_DATA_ROOT=$INTERLINK_DATA_ROOT"
echo "  INTERLINK_NODE_NAME=$INTERLINK_NODE_NAME"
echo "  SLURM_ACCOUNT=$SLURM_ACCOUNT"
echo "  SLURM_PARTITION=$SLURM_PARTITION"

echo "[STEP 1] Running kubernetes node setup"
bash "$SCRIPT_DIR/1-kubernetes.sh"

echo "[STEP 2] Installing Argo components"
bash "$SCRIPT_DIR/2-argo.sh"

echo "[STEP 3] Installing InterLink bridge"
bash "$SCRIPT_DIR/3-bridge.sh"

echo "Kubernetes infrastructure setup complete. Workflow templates are not installed automatically."
